#!/usr/bin/env node
// The page's scripts (public/js/*.js and public/setup.js) are plain scripts that
// share one global scope: a name defined at the top of one file is used in the
// others. ESLint's no-undef needs to know them, so this writes every top-level
// const, let, var, function, class and window.X name into scripts/page-globals.json, which
// eslint.config.js reads. Run it when a page script gains or loses a shared
// name (npm run lint runs it first). A name no file defines then fails lint.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as espree from 'espree';   // ESLint's own parser (a dev dependency, like ESLint)

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'scripts', 'page-globals.json');
const files = [join(ROOT, 'public', 'setup.js'), ...readdirSync(join(ROOT, 'public', 'js')).filter((f) => f.endsWith('.js')).sort().map((f) => join(ROOT, 'public', 'js', f))];

function patternNames(p, into) {
  if (!p) return;
  if (p.type === 'Identifier') into.push(p.name);
  else if (p.type === 'ObjectPattern') for (const prop of p.properties) patternNames(prop.type === 'RestElement' ? prop.argument : prop.value, into);
  else if (p.type === 'ArrayPattern') for (const el of p.elements) patternNames(el, into);
  else if (p.type === 'AssignmentPattern') patternNames(p.left, into);
  else if (p.type === 'RestElement') patternNames(p.argument, into);
}

const byFile = {};
for (const f of files) {
  const ast = espree.parse(readFileSync(f, 'utf8'), { ecmaVersion: 2024, sourceType: 'script', loc: false });
  const names = [];
  for (const node of ast.body) {
    if (node.type === 'VariableDeclaration') for (const d of node.declarations) patternNames(d.id, names);
    else if (node.type === 'FunctionDeclaration' || node.type === 'ClassDeclaration') names.push(node.id.name);
    // setup.js publishes its registry as window.SETUP = [...]: the same shared scope.
    else if (node.type === 'ExpressionStatement' && node.expression.type === 'AssignmentExpression') {
      const l = node.expression.left;
      if (l.type === 'MemberExpression' && !l.computed && l.object.type === 'Identifier' && ['window', 'globalThis', 'self'].includes(l.object.name)) names.push(l.property.name);
    }
  }
  byFile[relative(ROOT, f).replaceAll('\\', '/')] = names;
}
// Two page scripts declaring the same top-level name is a SyntaxError in the
// browser ("already been declared"), and the second script then does not load
// at all. Fail here instead.
const seen = new Map(), clashes = [];
for (const [file, names] of Object.entries(byFile)) for (const n of new Set(names)) {
  if (seen.has(n)) clashes.push(`${n}: ${seen.get(n)} and ${file}`);
  else if (!seen.has(n)) seen.set(n, file);
}
if (clashes.length) { console.error('The same name is declared in two page scripts (the second would not load):\n  ' + clashes.join('\n  ')); process.exit(1); }
const all = [...new Set(Object.values(byFile).flat())].sort();
writeFileSync(OUT, JSON.stringify({ note: 'Generated by scripts/page-globals.mjs: the names the page scripts share. Do not edit by hand.', names: all, files: byFile }, null, 2) + '\n');
console.log(`${all.length} shared names from ${files.length} page scripts, in ${relative(ROOT, OUT)}.`);
